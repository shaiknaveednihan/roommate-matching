CREATE TABLE IF NOT EXISTS users (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email            TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash    TEXT NOT NULL,
  name             TEXT,
  age              INTEGER,
  location         TEXT,
  gender           TEXT,
  snoring          TEXT,
  lights           TEXT,
  overnight_guests TEXT,
  chores           TEXT,
  budget           TEXT,
  cleanliness      TEXT,
  sleep            TEXT,
  social           TEXT,
  smoking          TEXT,
  alcohol          TEXT,
  noise            TEXT,
  guests           TEXT,
  food             TEXT,
  room_type        TEXT,
  conflict         TEXT,
  hobbies          TEXT NOT NULL DEFAULT '[]',   -- JSON array
  bio              TEXT NOT NULL DEFAULT '',
  profile_complete INTEGER NOT NULL DEFAULT 0,   -- 0 until questionnaire is submitted
  created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  token      TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL                    -- unix ms
);

CREATE TABLE IF NOT EXISTS reports (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reported_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reason      TEXT NOT NULL,
  details     TEXT NOT NULL DEFAULT '',
  status      TEXT NOT NULL DEFAULT 'open',      -- open | dismissed | upheld
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (reporter_id, reported_id)              -- one report per person per profile
);

CREATE TABLE IF NOT EXISTS messages (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body         TEXT NOT NULL,
  CHECK (sender_id != recipient_id)
);
CREATE INDEX IF NOT EXISTS messages_participants
  ON messages (sender_id, recipient_id, id);
CREATE INDEX IF NOT EXISTS messages_recipient
  ON messages (recipient_id, sender_id, id);
